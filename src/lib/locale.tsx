function readPreference(): LocalePreference {
  try {
    const saved = localStorage.getItem(STORAGE_KEY);
    if (saved === "en" || saved === "pt-BR") return saved;
  } catch {
    // Storage may be unavailable in a restricted browser context.
  }
  return "system";
}

function systemLocale(): Locale {
  return typeof navigator !== "undefined" && navigator.language.toLowerCase().startsWith("pt") ? "pt-BR" : "en";
}

/** Translate outside React components, such as socket listeners and toasts. */
// eslint-disable-next-line react-refresh/only-export-components
export function translateLocaleMessage(message: string, localeOverride?: Locale, params?: Record<string, string | number>): string {
  const preference = inMemoryPreference ?? readPreference();
  const locale = localeOverride ?? (preference === "system" ? systemLocale() : preference);
  const translated = locale === "pt-BR" ? (ptBR[message] ?? ptBRSettings[message]) : undefined;
  if (params) {
    const template = translated ?? message;
    return template.replace(/\{(\w+)\}/g, (placeholder, key: string) =>
      key in params ? String(params[key]) : placeholder,
    );
  }
  if (locale !== "pt-BR") return message;
  if (translated) return translated;
  let match: RegExpMatchArray | null;
  if (message.startsWith("Enable ")) return `Ativar ${ptBR[message.slice(7)] ?? ptBRSettings[message.slice(7)] ?? message.slice(7)}`;
  match = message.match(/^Please wait (\d+) seconds\.\.\.$/);
  if (match) return `Aguarde ${match[1]} segundos…`;
  match = message.match(/^Message #(.+)$/);
  if (match) return `Mensagem em #${match[1]}`;
  match = message.match(/^Message (.+) \(not encrypted\)$/);
  if (match) return `Mensagem para ${match[1]} (não criptografada)`;
  if (/^\d+ new$/.test(message)) return `${message.slice(0, -4)} novas`;
  match = message.match(/^Server responded with (\d{3})$/);
  if (match) return `O servidor respondeu com o código ${match[1]}`;
  match = message.match(/^Failed to join server: (.+)$/);
  if (match) return `Falha ao entrar no servidor: ${match[1]}`;
  match = message.match(/^Upload failed \((\d{3})\)$/);
  if (match) return `Falha no envio (código ${match[1]})`;
  match = message.match(/^Your avatar didn't upload to (\d+) of your (\d+) servers\. Try again in a moment\.$/);
  if (match) return `Não foi possível enviar seu avatar para ${match[1]} de ${match[2]} servidores. Tente novamente em instantes.`;
  match = message.match(/^Avatar removed, but (\d+) of your (\d+) servers still show the old one\.$/);
  if (match) return `O avatar foi removido, mas ${match[1]} de ${match[2]} servidores ainda mostram o antigo.`;
  match = message.match(/^Your video goes to the (\d+) of (\d+) servers that take one\. The others keep your current avatar\.$/);
  if (match) return `O vídeo será enviado para ${match[1]} dos ${match[2]} servidores que aceitam esse formato. Os outros manterão seu avatar atual.`;
  match = message.match(/^Synced, but avatar failed on (\d+)\/(\d+) servers?$/);
  if (match) return `Sincronizado, mas o avatar falhou em ${match[1]} de ${match[2]} servidores.`;
  match = message.match(/^Synced, but the avatar could not be cleared on (\d+)\/(\d+) servers?$/);
  if (match) return `Sincronizado, mas não foi possível remover o avatar de ${match[1]} de ${match[2]} servidores.`;
  match = message.match(/^Profile synced to (\d+) servers?$/);
  if (match) return `Perfil sincronizado com ${match[1]} servidor(es).`;
  match = message.match(/^Could not copy that avatar: (.+)$/);
  if (match) return `Não foi possível copiar esse avatar: ${translateLocaleMessage(match[1], locale)}`;
  match = message.match(/^(.+) answered in (\d+) ms$/);
  if (match) return `${match[1]} respondeu em ${match[2]} ms`;
  match = message.match(/^(.+) (no answer within \d+s|could not connect)\. Chat and joining go over this address, so nothing will work until it does\.$/);
  if (match) return `${match[1]} ${translateLocaleMessage(match[2], locale)}. O chat e a entrada no servidor dependem deste endereço; nada vai funcionar até que ele responda.`;
  match = message.match(/^no answer within (\d+)s$/);
  if (match) return `sem resposta em ${match[1]} s`;
  match = message.match(/^(\d+) of (\d+) answered, which is normal if the others are for people on a different network\.$/);
  if (match) return `${match[1]} de ${match[2]} responderam; é normal que os outros endereços sejam para pessoas em outra rede.`;
  match = message.match(/^All (\d+) advertised addresses answered\.$/);
  if (match) return `Todos os ${match[1]} endereços anunciados responderam.`;
  match = message.match(/^None of the (\d+) addresses advertised for voice can be reached from here\.$/);
  if (match) return `Nenhum dos ${match[1]} endereços anunciados para voz pode ser acessado daqui.`;
  match = message.match(/^Could not open a connection to (.+)\.$/);
  if (match) return `Não foi possível abrir uma conexão com ${match[1]}.`;
  match = message.match(/^(.+) answered a health check but never completed a connection\.$/);
  if (match) return `${match[1]} respondeu à verificação de disponibilidade, mas não concluiu a conexão.`;
  match = message.match(/^Connected to (.+)\.$/);
  if (match) return `Conectado a ${match[1]}.`;
  match = message.match(/^(.+) refused the connection\.$/);
  if (match) return `${match[1]} recusou a conexão.`;
  match = message.match(/^UDP leaves this machine: (\d+) local and (\d+) public candidates?\. This does not prove the server's media port is open, only that this end can send\.$/);
  if (match) return `O UDP sai deste computador: ${match[1]} candidato(s) local(is) e ${match[2]} público(s). Isso não confirma que a porta de mídia do servidor esteja aberta, apenas que este lado consegue enviar dados.`;
  match = message.match(/^Found (\d+) local candidates? but no public one, so STUN got no answer\. On mobile data this is expected and voice will not connect; on Wi-Fi it usually means UDP is blocked\.$/);
  if (match) return `Encontrado(s) ${match[1]} candidato(s) local(is), mas nenhum público; o STUN não respondeu. Isso é esperado usando dados móveis e impede chamadas de voz. No Wi-Fi, geralmente significa que o UDP está bloqueado.`;
  match = message.match(/^Negotiation started but never connected within (\d+)s\. Signalling works and media does not, which almost always means the UDP port is closed or the network drops UDP\.$/);
  if (match) return `A negociação começou, mas não conectou em ${match[1]} s. A sinalização funciona, mas a mídia não; quase sempre isso significa que a porta UDP está fechada ou que a rede descarta UDP.`;
  match = message.match(/^Connected\. Media took (.+) → (.+), reaching the server at (.+):(\d+) over ([A-Z]+)\.$/);
  if (match) return `Conectado. A mídia passou por ${match[1]} → ${match[2]} e chegou ao servidor em ${match[3]}:${match[4]} usando ${match[5]}.`;
  match = message.match(/^The voice server refused the test room: (.+)\.$/);
  if (match) return `O servidor de voz recusou a sala de teste: ${translateLocaleMessage(match[1], locale)}.`;
  match = message.match(/^The server would not open a test room: (.+)$/);
  if (match) return `O servidor não abriu uma sala de teste: ${translateLocaleMessage(match[1], locale)}`;
  match = message.match(/^The test call could not be started: (.+)$/);
  if (match) return `Não foi possível iniciar a chamada de teste: ${translateLocaleMessage(match[1], locale)}`;
  match = message.match(/^Notify up to (\d+) people\?$/);
  if (match) return `Notificar até ${match[1]} pessoas?`;
  match = message.match(/^@everyone pings everyone who can read this channel, and (\d+) of them are online right now\. Each of them gets a notification\.$/);
  if (match) return `@everyone notifica todas as pessoas que podem ler este canal; ${match[1]} estão online agora. Todas receberão uma notificação.`;
  match = message.match(/^This deletes the message and the (\d+) replies? in its thread\. You can't undo it\.$/);
  if (match) return `Esta ação exclui a mensagem e ${match[1]} resposta(s) da conversa. Não é possível desfazê-la.`;
  match = message.match(/^Merge into (.+)\?$/);
  if (match) return `Mesclar em ${match[1]}?`;
  match = message.match(/^Keep (.+)$/);
  if (match) return `Manter ${match[1]}`;
  match = message.match(/^(.+) is the same server as (.+), reached at a different address\.$/);
  if (match) return `${match[1]} é o mesmo servidor que ${match[2]}, acessado por outro endereço.`;
  match = message.match(/^(.+) are the same server as (.+), reached at different addresses\.$/);
  if (match) return `${match[1]} são o mesmo servidor que ${match[2]}, acessados por outros endereços.`;
  match = message.match(/^Keeping (.+) removes the other (entry|entries) from your list\. You stay a member either way — this is your list, not the server\. Your place in the list and the channel you were last in are kept\.$/);
  if (match) return `Manter ${match[1]} remove ${match[2] === "entry" ? "a outra entrada" : "as outras entradas"} da sua lista. Você continua sendo membro; isso altera apenas a sua lista, não o servidor. Sua posição na lista e o último canal acessado serão mantidos.`;
  if (message.startsWith("A message every ")) return `Uma mensagem a cada ${message.slice(16)}`;
  if (message.startsWith("Signed in as ")) return `Conectado como ${message.slice(13)}`;
  if (message.startsWith("Could not connect to the server: ")) {
    return `Não foi possível conectar ao servidor: ${message.slice("Could not connect to the server: ".length)}`;
  }
  if (message.startsWith("WebSocket connection failed — retrying with fallback. If this persists, the server may be unreachable.")) {
    const detail = message.match(/\((.*)\)$/)?.[1];
    return `A conexão WebSocket falhou. Tentando uma alternativa; se o problema continuar, o servidor pode estar inacessível.${detail ? ` (${detail})` : ""}`;
  }
  if (message.startsWith("Not connected to ") && message.endsWith(", so it cannot be told you are leaving.")) {
    return `Sem conexão com ${message.slice("Not connected to ".length, -", so it cannot be told you are leaving.".length)}. Não foi possível avisar que você está saindo.`;
  }
  if (message.startsWith("Stopped reconnecting to ") && message.endsWith(". It keeps ending your session.")) {
    return `A reconexão com ${message.slice("Stopped reconnecting to ".length, -". It keeps ending your session.".length)} foi interrompida porque sua sessão continua sendo encerrada.`;
  }
  if (message.startsWith("Your session on ") && message.endsWith(" was ended.")) {
    return `Sua sessão em ${message.slice("Your session on ".length, -" was ended.".length)} foi encerrada.`;
  }
  if (message.startsWith("Could not prove who you are to this server: ")) {
    return `Não foi possível confirmar sua identidade neste servidor: ${message.slice("Could not prove who you are to this server: ".length)}`;
  }
  if (message.startsWith("Your avatar will be removed from ") && message.endsWith(". This action cannot be undone.")) {
    const server = message.slice("Your avatar will be removed from ".length, -". This action cannot be undone.".length);
    return `Seu avatar será removido de ${server}. Esta ação não pode ser desfeita.`;
  }
  if (message.startsWith("This is how other people on ") && message.endsWith(" see you.")) {
    return `É assim que as outras pessoas em ${message.slice(28, -9)} veem você.`;
  }
  return message;
}

/** Provides the selected interface locale and the translations bundled with the client. */
export function LocaleProvider({ children }: { children: ReactNode }) {
  const [preference, setPreferenceState] = useState<LocalePreference>(readPreference);
  const locale = preference === "system" ? systemLocale() : preference;

  const setPreference = useCallback((next: LocalePreference) => {
    inMemoryPreference = next;
    setPreferenceState(next);
    try {
      if (next === "system") localStorage.removeItem(STORAGE_KEY);
      else localStorage.setItem(STORAGE_KEY, next);
    } catch {
      // The selection still applies for this session when storage is unavailable.
    }
  }, []);

  useEffect(() => {
    document.documentElement.lang = locale === "pt-BR" ? "pt-BR" : "en";
  }, [locale]);

  const t = useCallback((message: string, params?: Record<string, string | number>) => translateLocaleMessage(message, locale, params), [locale]);
  const value = useMemo(() => ({ locale, preference, setPreference, t }), [locale, preference, setPreference, t]);
  return <LocaleContext.Provider value={value}>{children}</LocaleContext.Provider>;
}
